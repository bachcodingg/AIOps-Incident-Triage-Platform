-- Customer reviews. A product lookup shows its average rating, so every lookup
-- aggregates this table through idx_review_product. Fault F12 is a release that
-- drops the index (see ReviewIndex.java): the same lookup then scans the table.
CREATE TABLE review (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT   NOT NULL,
    stars      SMALLINT NOT NULL CHECK (stars BETWEEN 1 AND 5)
);
